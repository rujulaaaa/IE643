#!/bin/bash
# Experiment 2, steps 2-8 after the Phase 2 sweeps (docs/experiment2.md).
#
#   [KAGGLE_USER=<account>] bash scripts/exp2_orchestrate.sh [log dir, default results/exp2/logs]
#
# Without KAGGLE_USER it runs the local steps (analysis, quality gate, selection, grid) and stops before
# building any kernel; no account is assumed. The Kaggle CLI must be logged in as that account.
# ELSEWHERE="<slug> ..." names kernels run on another account and downloaded separately (into
# results/kaggle/<slug>/ with .download_ok): they are neither built nor pushed, only waited for.
#
# Safe to re-run: every step is skipped when its output exists, and a kernel that already exists on Kaggle is
# never pushed again (a second push would start a new version and discard the running one). It stops with
# "FAILED ..." (exit 1) when a kernel errors, a download cannot be verified, an analysis fails or the disk is
# nearly full, so the next step never runs on partial data. Do not edit this file while it runs: bash reads
# scripts incrementally.
set -uo pipefail
C=$(cd "$(dirname "$0")/.." && pwd)
SCR=${1:-$C/results/exp2/logs}         # queue/wait logs; on disk, so they survive a reboot
QUEUE=$C/scripts/kaggle_queue.sh
WAIT=$C/scripts/kaggle_wait.sh
mkdir -p "$SCR"
K=~/kaggle/.venv/bin/kaggle
R=$C/results/kaggle
E=$C/results/exp2
PY="env -u PYTHONPATH PYTHONPATH=$C/src $C/.venv/bin/python"
USER_K=${KAGGLE_USER:-}
ELSEWHERE=" ${ELSEWHERE:-} "
elsewhere() { [[ "$ELSEWHERE" == *" $1 "* ]]; }
CELLS=(sd15_mm2 epicrealism_mm2 sd15_mm3 epicrealism_mm3)
cd "$C"
log() { echo "$(date '+%F %T') $*"; }
fail() { log "FAILED $*"; exit 1; }
slug() { echo "vdprobe-exp2-${1//_/-}"; }
celldir() { echo "$R/$(slug "$1")/out/$1"; }
cellcfg() { [ "$1" = sd15_mm2 ] && echo "" || echo "--config configs/variants/$1.yaml"; }
kstatus() { $K kernels status "$USER_K/$1" 2>&1 | tail -1; }
exists() { kstatus "$1" | grep -q KernelWorkerStatus; }
disk_ok() { [ "$(df -BG --output=avail "$C" | tail -1 | tr -dc 0-9)" -ge "${1:-6}" ]; }

# 1-2. per-cell analysis as each cell's verified download appears
pending=("${CELLS[@]}")
while [ ${#pending[@]} -gt 0 ]; do
  left=()
  for c in "${pending[@]}"; do
    d=$(celldir "$c")
    [ -f "$R/$(slug "$c")/.download_ok" ] || case "$(kstatus "$(slug "$c")")" in
      *ERROR*|*CANCEL*) fail "sweep kernel $(slug "$c") ended in error";; esac
    if [ -f "$R/$(slug "$c")/.download_ok" ] && [ "$(ls "$d"/*/manifest.json 2>/dev/null | wc -l)" -ge 4 ]; then
      if [ ! -f "$E/$c/exp2_analysis.json" ]; then
        log "analysis $c"
        $PY scripts/exp2_analysis.py "$d" --out "$E/$c" --n-jobs ${NJOBS:-4} || fail "analysis $c"
      fi
    elif [ -f "$R/$(slug "$c")/.download_ok" ]; then
      fail "download of $c marked complete but only $(ls "$d"/*/manifest.json 2>/dev/null | wc -l) of 4 groups present"
    else
      left+=("$c")
    fi
  done
  pending=("${left[@]}")
  [ ${#pending[@]} -gt 0 ] && sleep 120
done
log "all four cells analysed"

# 3. quality gate -> primary cell and ladder verbs
if [ ! -f "$E/quality/quality.json" ]; then
  log "quality gate"
  $PY scripts/exp2_quality.py $(for c in "${CELLS[@]}"; do celldir "$c"; done) --out "$E/quality" || fail "quality"
fi
PRIMARY=$($PY -c "import json; print(json.load(open('$E/quality/quality.json'))['decision']['primary_cell'])") || fail "reading quality"
VERBS=$($PY -c "import json; print(', '.join(json.load(open('$E/quality/quality.json'))['decision']['ladder_verbs']))") || fail "reading verbs"
log "primary cell $PRIMARY, ladder verbs [$VERBS]"

# 5. selection (D-35) and the 2x2 grid
if [ ! -f "$E/selection/candidates.json" ]; then
  $PY scripts/exp2_select.py "$E/$PRIMARY" --out "$E/selection" || fail "selection"
fi
if [ ! -f "$E/grid/grid.json" ]; then
  $PY scripts/exp2_grid.py --cells $(for c in "${CELLS[@]}"; do echo "$c=$(celldir "$c")"; done) --out "$E/grid" \
    || log "grid failed (non-blocking; re-run scripts/exp2_grid.py by hand)"
fi

[ -n "$USER_K" ] || { log "local steps done; set KAGGLE_USER=<account> to build and queue the Kaggle kernels"; exit 0; }

# 6. build the patching, erasure and ladder kernels on the primary cell (only those not yet on Kaggle)
CFG=$(cellcfg "$PRIMARY")
cp "$E/selection/candidates.json" configs/exp2_candidates.json
sed -i "s/^verbs: .*/verbs: [$VERBS]     # set by the Phase 1 quality gate (D-35)/" configs/ladder.yaml
read -r EC1 ES1 EC2 ES2 <<<"$($PY -c "
import json; c = json.load(open('configs/exp2_candidates.json'))['candidates']
print(c[0]['coords'][0], ','.join(map(str, c[0]['steps'])), c[1]['coords'][0], ','.join(map(str, c[1]['steps'])))")" \
  || fail "reading candidates"
build() { $PY scripts/kaggle_run.py --user $USER_K --build-only "$@" > /dev/null || fail "build $2"; }
PATCH="scripts/exp2_patching.py --candidates configs/exp2_candidates.json $CFG"
declare -A NEED=([vdprobe-exp2-patch-a]=2 [vdprobe-exp2-patch-b]=2 [vdprobe-exp2-erase]=2 [vdprobe-exp2-ladder]=2)
TOPUSH=()
for s in vdprobe-exp2-patch-a vdprobe-exp2-patch-b vdprobe-exp2-erase vdprobe-exp2-ladder; do
  if [ -f "$R/$s/.download_ok" ] || elsewhere "$s" || exists "$s"; then continue; fi
  case $s in
    vdprobe-exp2-patch-a) build --slug $s --job "$PATCH --shard 0/4 --out /kaggle/working/out/s0" \
                                          --job "$PATCH --shard 1/4 --out /kaggle/working/out/s1" ;;
    vdprobe-exp2-patch-b) build --slug $s --job "$PATCH --shard 2/4 --out /kaggle/working/out/s2" \
                                          --job "$PATCH --shard 3/4 --out /kaggle/working/out/s3" ;;
    vdprobe-exp2-erase) build --slug $s --job "scripts/exp2_erasure.py --coord $EC1 --steps ${ES1//,/ } $CFG --out /kaggle/working/out/c1" \
                                        --job "scripts/exp2_erasure.py --coord $EC2 --steps ${ES2//,/ } $CFG --out /kaggle/working/out/c2" ;;
    vdprobe-exp2-ladder) build --slug $s --job "scripts/probe_sweep.py --exp2 --set ladder --seeds 42 $CFG --out /kaggle/working/out/$PRIMARY" \
                                         --job "scripts/probe_sweep.py --exp2 --set ladder --seeds 1337 $CFG --out /kaggle/working/out/$PRIMARY" ;;
  esac
  TOPUSH+=("$s")
done
if ! disk_ok 6; then
  # files no Experiment 2 analysis reads, all re-downloadable from the Kaggle kernels: final latents and the
  # 2048-dim refined sketches. Removed only when the disk would otherwise be too full for the ladder outputs.
  log "less than 6 GB free: removing latents.pt and sketches_refined.pt (unused, still on Kaggle)"
  find "$R"/vdprobe-exp2-*/out \( -name latents.pt -o -name sketches_refined.pt \) -print -delete
  disk_ok 5 || fail "less than 5 GB free on disk even after pruning"
fi

# 7. queue (two GPU slots, retried until a slot and quota are free) and wait; each download verified
[ ${#TOPUSH[@]} -gt 0 ] && { log "queueing ${TOPUSH[*]}"; "$QUEUE" "${TOPUSH[@]}" > "$SCR/queue_exp2.log" 2>&1 & }
waitfor() {   # slug -> 0 when its download is verified, 1 when the kernel errored or the download failed
  [ -f "$R/$1/.download_ok" ] && return 0
  if elsewhere "$1"; then until [ -f "$R/$1/.download_ok" ]; do sleep 120; done; return 0; fi
  until exists "$1"; do sleep 120; done
  "$WAIT" "$1" "$R/$1" "${NEED[$1]}" > "$SCR/wait_$1.log" 2>&1 || return 1
  case "$(kstatus "$1")" in *COMPLETE*) return 0;; *) return 1;; esac
}
waitfor vdprobe-exp2-patch-a & W1=$!
waitfor vdprobe-exp2-patch-b & W2=$!
waitfor vdprobe-exp2-erase & W3=$!
waitfor vdprobe-exp2-ladder & W4=$!
wait $W1 || fail "patch-a (see $SCR/wait_vdprobe-exp2-patch-a.log)"
wait $W2 || fail "patch-b (see $SCR/wait_vdprobe-exp2-patch-b.log)"
wait $W3 || fail "erase (see $SCR/wait_vdprobe-exp2-erase.log)"
log "patching and erasure downloaded"

# 8. the verdict, then the ladder analysis
if [ ! -f "$E/verdict/verdict.json" ]; then
  $PY scripts/exp2_verdict.py --analysis "$E/$PRIMARY" --candidates configs/exp2_candidates.json \
    --patching "$R/vdprobe-exp2-patch-a" "$R/vdprobe-exp2-patch-b" --erasure "$R/vdprobe-exp2-erase" \
    --sweep "$(celldir "$PRIMARY")" --out "$E/verdict" || fail "verdict"
fi
log "verdict written"
wait $W4 || fail "ladder (see $SCR/wait_vdprobe-exp2-ladder.log)"
if [ ! -f "$E/ladder/ladder.json" ]; then
  $PY scripts/exp2_ladder.py "$R/vdprobe-exp2-ladder/out/$PRIMARY" --out "$E/ladder" || fail "ladder analysis"
fi
log "EXPERIMENT 2 STEPS 1-8 DONE"
